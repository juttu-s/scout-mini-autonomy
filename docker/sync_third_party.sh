#!/bin/bash
# Record the third-party sources the images build from: upstream URL + exact commit (third_party.repos) and the
# local changes as patches (patches/<name>.patch). Run after changing or updating any third-party package, then
# commit; the Dockerfiles clone these commits and apply the patches, so images never depend on this machine's files.
set -e
cd "$(dirname "$0")"
R=~/ros_utils
# name                        path (relative to ~/ros_utils)
LIST="vision_msgs                  detection_ws/src/vision_msgs
realsense-ros                realsense_ws/src/realsense-ros
librealsense                 librealsense
scout_ros                    scout_ws/src/scout_ros
ugv_sdk                      scout_ws/src/ugv_sdk
livox_ros_driver2            ws_livox/src/livox_ros_driver2
Livox-SDK2                   Livox-SDK2
direct_lidar_inertial_odometry dlio_ws/src/direct_lidar_inertial_odometry
ndt_omp                      nav_ws/src/ndt_omp
fast_gicp                    nav_ws/src/fast_gicp
hdl_localization             nav_ws/src/hdl_localization
hdl_global_localization      nav_ws/src/hdl_global_localization"
{
  echo "# Generated by sync_third_party.sh on $(date -I). Clone each at 'version'; apply patches/<name>.patch if present."
  echo "repositories:"
  while read -r name path; do
    d=$R/$path
    url=$(git -C "$d" remote get-url origin)
    rev=$(git -C "$d" rev-parse HEAD)
    echo "  $name:"
    echo "    type: git"
    echo "    url: $url"
    echo "    version: $rev"
    if [ -n "$(git -C "$d" diff HEAD --stat)" ]; then
      git -C "$d" diff HEAD > "patches/$name.patch"
      echo "    patch: patches/$name.patch"
    else
      rm -f "patches/$name.patch"
    fi
    untracked=$(git -C "$d" ls-files --others --exclude-standard | grep -v -E '(^|/)(build|devel|__pycache__)/' || true)
    [ -n "$untracked" ] && echo "WARNING: $name has untracked files not in the patch: $untracked" >&2
  done <<< "$LIST"
} > third_party.repos
echo "third_party.repos: $(grep -c 'type: git' third_party.repos) repositories, $(ls patches | wc -l) patches"
