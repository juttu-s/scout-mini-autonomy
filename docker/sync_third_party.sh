#!/bin/bash
# Record the third-party sources the images build from, one pin per package in pins/:
#   pins/<name>.repos   upstream URL + exact commit (vcstool format)
#   pins/<name>.patch   this machine's local changes, if any
# third_party.repos is the same information in one file, for reading. The Dockerfiles copy only the pins each
# step needs, so changing one package rebuilds only the layers that use it (e.g. adding vision_opencv doesn't
# throw away the cached librealsense build). Run after changing or updating a third-party package, then commit.
set -e
cd "$(dirname "$0")"
R=~/ros_utils
# name                        path (relative to ~/ros_utils)
LIST="vision_msgs                  detection_ws/src/vision_msgs
realsense-ros                realsense_ws/src/realsense-ros
vision_opencv                realsense_ws/src/vision_opencv
librealsense                 librealsense
scout_ros                    scout_ws/src/scout_ros
ugv_sdk                      scout_ws/src/ugv_sdk
livox_ros_driver2            ws_livox/src/livox_ros_driver2
Livox-SDK2                   Livox-SDK2
direct_lidar_inertial_odometry dlio_ws/src/direct_lidar_inertial_odometry
ndt_omp                      nav_ws/src/ndt_omp
fast_gicp                    nav_ws/src/fast_gicp
hdl_localization             nav_ws/src/hdl_localization
hdl_global_localization      nav_ws/src/hdl_global_localization"
mkdir -p pins
rm -f pins/*.repos pins/*.patch
{
  echo "# Generated by sync_third_party.sh on $(date -I) (summary; the builds use pins/<name>.repos + .patch)."
  echo "repositories:"
  while read -r name path; do
    d=$R/$path
    entry="  $name:
    type: git
    url: $(git -C "$d" remote get-url origin)
    version: $(git -C "$d" rev-parse HEAD)"
    if [ -n "$(git -C "$d" diff HEAD --stat)" ]; then
      git -C "$d" diff HEAD > "pins/$name.patch"
      entry="$entry
    patch: $name.patch"
    fi
    printf 'repositories:\n%s\n' "$entry" > "pins/$name.repos"
    echo "$entry"
    untracked=$(git -C "$d" ls-files --others --exclude-standard | grep -v -E '(^|/)(build|devel|__pycache__)/' || true)
    [ -n "$untracked" ] && echo "WARNING: $name has untracked files not in the patch: $untracked" >&2
  done <<< "$LIST"
} > third_party.repos
echo "pins: $(ls pins/*.repos | wc -l) packages, $(ls pins/*.patch 2>/dev/null | wc -l) patches"
